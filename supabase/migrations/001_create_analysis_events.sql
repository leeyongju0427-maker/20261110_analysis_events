-- 마음결 (Maeumgyeol) 감성 분석 서비스 - 통계 메타데이터 테이블 생성 쿼리
-- 
-- [개인정보 및 보안 원칙]
-- 1. 사용자가 입력한 '원문 텍스트'나 AI가 생성한 '분석 이유'는 절대 DB에 저장하지 않습니다.
-- 2. IP 주소, 사용자 이메일, 개인 식별자 역시 저장하지 않습니다.
-- 3. 오직 서비스 운영 통계(감성 분포, 신뢰도 구간, 사용 모델) 목적으로만 익명 데이터를 기록합니다.
-- 4. RLS(Row Level Security)를 활성화하여 브라우저에서 직접 데이터를 조회/조작하지 못하도록 차단합니다.
--    (서버 백엔드의 Service Role Key를 통해서만 안전하게 저장됩니다.)
-- ==============================================================================

-- 1. analysis_events (감성 분석 통계 이벤트) 테이블 생성
create table if not exists public.analysis_events (
  -- 각 이벤트의 고유 식별 번호 (자동 1씩 증가)
  id bigint generated by default as identity primary key,

  -- 데이터가 저장된 시각 (기본값: 현재 시각)
  created_at timestamptz not null default now(),

  -- 감성 분석 결과 (positive: 긍정, negative: 부정, neutral: 중립만 허용)
  sentiment text not null check (sentiment in ('positive', 'negative', 'neutral')),

  -- 신뢰도 구간 (0-49: 낮음, 50-69: 보통, 70-84: 높음, 85-100: 매우 높음)
  confidence_bucket text not null check (
    confidence_bucket in ('0-49', '50-69', '70-84', '85-100')
  ),

  -- 사용된 AI 모델명 (예: gpt-4o-mini 등)
  model_name text
);

-- 2. 테이블 설명 주석 등록 (관리 및 문서화 용도)
comment on table public.analysis_events is '마음결 감성 분석 서비스의 익명 통계 집계 메타데이터 테이블 (원문 미저장)';
comment on column public.analysis_events.id is '이벤트 고유 식별 번호';
comment on column public.analysis_events.created_at is '분석 이벤트 발생 일시';
comment on column public.analysis_events.sentiment is '판정된 감성 (positive / negative / neutral)';
comment on column public.analysis_events.confidence_bucket is '신뢰도 점수 구간 (0-49 / 50-69 / 70-84 / 85-100)';
comment on column public.analysis_events.model_name is '분석에 사용된 AI 모델명';

-- 3. Row Level Security (행 단위 보안 정책, RLS) 활성화
-- RLS를 활성화하면 기본적으로 모든 공개(anon) 접근이 차단됩니다.
alter table public.analysis_events enable row level security;

-- [참고] 브라우저(anon key)에서 직접 읽거나 쓰는 공개 정책(Policy)은 일체 등록하지 않습니다.
-- 백엔드 서버(Node.js)가 가진 'SUPABASE_SERVICE_ROLE_KEY'를 통해서만 이 테이블에 안전하게 INSERT가 가능합니다.

